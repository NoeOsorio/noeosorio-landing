// and the moving parts (src/home/sections/card-motion/galaxy.ts: the five ringed orbit nodes and the four lime points).
// Run from the repo root:  node scripts/cards/gen/galaxy-split.mjs
import { chromium } from '/private/tmp/claude-501/-Users-noe-Dev-Web/2507de66-3b5f-4d4b-b0d4-cab428c99f73/scratchpad/refs/node_modules/playwright/index.mjs';
import { execSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';

const root = process.cwd();
const exe = execSync('ls -d ~/Library/Caches/ms-playwright/chromium_headless_shell-1217/chrome-headless-shell-mac-arm64/chrome-headless-shell').toString().trim();
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'galaxy-split-'));
const b = await chromium.launch({ headless: true, executablePath: exe });
const p = await b.newPage({ deviceScaleFactor: 2, viewport: { width: 700, height: 600 } });
await p.goto('file://' + root + '/scripts/cards/galaxy.html');
await p.addStyleTag({ content: 'html,body,.stage,.stagewrap{background:transparent!important}.pass::before,.pass::after{display:none!important}.title,.nfc,svg.chip,.num,.bottom{visibility:hidden!important}' });
await p.evaluate(() => document.fonts.ready);
await p.waitForTimeout(800);

// 1. Find the moving parts in the first card (the full one) and hide them for the base.
const parts = await p.evaluate(() => {
  const art = document.querySelector('.card .art');
  const kids = [...art.children];
  const num = (e, a) => parseFloat(e.getAttribute(a));
  const nodes = [];
  kids.forEach((e, j) => {
    if (e.tagName !== 'ellipse') return;
    const cx = num(e, 'cx'), cy = num(e, 'cy');
    let s = j;
    while (s > 0) {
      const q = kids[s - 1];
      if (q.tagName === 'circle' && q.getAttribute('fill') === '#DCE9F0' && q.hasAttribute('opacity') && Math.hypot(num(q, 'cx') - cx, num(q, 'cy') - cy) < 30) s--; else break;
    }
    const els = kids.slice(s, j + 3); // satellite dots, ellipse, core, ring
    nodes.push({ cx, cy, html: els.map((x) => x.outerHTML), n: els.length });
    els.forEach((x) => (x.style.display = 'none'));
  });
  const limes = [];
  kids.forEach((e, j) => {
    if (e.tagName === 'circle' && e.getAttribute('fill') === '#D6F35C') {
      const els = [e, kids[j + 1]];
      limes.push({ cx: num(e, 'cx'), cy: num(e, 'cy'), html: els.map((x) => x.outerHTML) });
      els.forEach((x) => (x.style.display = 'none'));
    }
  });
  return { nodes, limes };
});
if (parts.nodes.length !== 5 || parts.limes.length !== 4) throw new Error('unexpected counts ' + parts.nodes.length + ' ' + parts.limes.length);

// 2. Base without them.
await p.waitForTimeout(200);
const png = path.join(tmp, 'galaxy.png');
await (await p.$('.card')).screenshot({ path: png, omitBackground: true });
await b.close();
execSync(`cwebp -quiet -q 86 -alpha_q 100 "${png}" -o "${root}/src/home/assets/cards/galaxy.webp"`);

// 3. Overlay SVG: one group per node and per lime point, in the same 520 x 328 space.
const r1 = (h) => h.replace(/-?\d+\.\d{2,}/g, (m) => String(Math.round(parseFloat(m) * 10) / 10));
const nodes = parts.nodes.map((n, i) => `<g data-n data-c="${n.cx} ${n.cy}">${r1(n.html.join(''))}</g>`).join('');
const limes = parts.limes.map((l) => `<g data-l>${r1(l.html.join(''))}</g>`).join('');
const svg = nodes + limes;

const ts = `// Porter Galaxy: the moving parts of the card (five ringed orbit nodes and four lime points).
// Generated by scripts/cards/gen/galaxy-split.mjs from the same source as src/home/assets/cards/galaxy.webp (dust, spiral, orbits, centre).
// At rest, this overlay on that base is the approved card. Build-up is about 1.3 s.
import { EASE, type CardMotion } from './index';

const svg = ${JSON.stringify(svg)};

// The disc is tilted: centre of the galaxy, tilt of its long axis and how flat it looks (measured from the orbit lines).
const CX = 358, CY = 128, PHI = (-17 * Math.PI) / 180, K = 0.394;

// Where a point on the disc ends up after turning th radians around the centre, in the plane of the disc.
function swing(x: number, y: number, th: number): [number, number] {
  const c = Math.cos(PHI), s = Math.sin(PHI);
  const dx = x - CX, dy = y - CY;
  const u = dx * c + dy * s, v = (-dx * s + dy * c) / K;
  const u2 = u * Math.cos(th) - v * Math.sin(th), v2 = (u * Math.sin(th) + v * Math.cos(th)) * K;
  return [CX + u2 * c - v2 * s, CY + u2 * s + v2 * c];
}

const motion: CardMotion = {
  id: 'porter-galaxy',
  svg,
  play(root, delay) {
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return [];
    const out: Animation[] = [];
    // Each node travels a short arc along its orbit into place while it fades in.
    const STEPS = 8, SWING = (-26 * Math.PI) / 180;
    root.querySelectorAll<SVGGElement>('[data-n]').forEach((g, i) => {
      const [x, y] = (g.dataset.c || '0 0').split(' ').map(Number);
      const frames: Keyframe[] = [];
      for (let k = 0; k <= STEPS; k++) {
        const t = k / STEPS, e = 1 - Math.pow(1 - t, 3);
        const [px, py] = swing(x, y, SWING * (1 - e));
        frames.push({ transform: \`translate(\${(px - x).toFixed(2)}px, \${(py - y).toFixed(2)}px)\`, opacity: Math.min(1, e * 1.5) });
      }
      out.push(g.animate(frames, { duration: 720, delay: delay + i * 100, easing: 'linear', fill: 'backwards' }));
    });
    // Then the lime points light up.
    root.querySelectorAll<SVGGElement>('[data-l]').forEach((g, i) => {
      g.style.transformBox = 'fill-box';
      g.style.transformOrigin = 'center';
      out.push(g.animate(
        [{ transform: 'scale(0.6)', opacity: 0 }, { transform: 'scale(1.25)', opacity: 1, offset: 0.55 }, { transform: 'scale(1)', opacity: 1 }],
        { duration: 400, delay: delay + 640 + i * 100, easing: EASE, fill: 'backwards' },
      ));
    });
    return out;
  },
};

export default motion;
`;
fs.writeFileSync(root + '/src/home/sections/card-motion/galaxy.ts', ts);
console.log('galaxy.ts bytes', ts.length, 'svg bytes', svg.length, 'groups', parts.nodes.length + parts.limes.length, 'node element counts', parts.nodes.map((n) => n.n));
